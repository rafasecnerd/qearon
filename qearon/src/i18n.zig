pub fn detectSystemLanguage(allocator: std.mem.Allocator) Language {
    const env_vars = [_][]const u8{ "LC_ALL", "LC_MESSAGES", "LANG" };

    for (env_vars) |var_name| {
        if (std.process.getEnvVarOwned(allocator, var_name)) |val| {
            defer allocator.free(val);
            if (val.len >= 2) {
                if (std.mem.startsWith(u8, val, "pt") or std.mem.indexOf(u8, val, "pt_") != null) {
                    return .pt;
                }
            }
        } else |_| {}
    }

    return .en;
}

fn openConfigLangFile(for_write: bool) ?std.fs.File {
    if (std.posix.getenv("HOME")) |home| {
        var buf: [512]u8 = undefined;
        const config_dir = std.fmt.bufPrint(&buf, "{s}/.config/qearon", .{home}) catch null;
        if (config_dir) |dir| {
            if (for_write) {
                std.fs.cwd().makePath(dir) catch {};
            }
            var path_buf: [512]u8 = undefined;
            const full_path = std.fmt.bufPrint(&path_buf, "{s}/lang", .{dir}) catch null;
            if (full_path) |fp| {
                if (for_write) {
                    if (std.fs.cwd().createFile(fp, .{})) |f| return f else |_| {}
                } else {
                    if (std.fs.cwd().openFile(fp, .{})) |f| return f else |_| {}
                }
            }
        }
    }
    if (for_write) {
        return std.fs.cwd().createFile(cache_file, .{}) catch null;
    } else {
        return std.fs.cwd().openFile(cache_file, .{}) catch null;
    }
}

pub fn getLanguage(allocator: std.mem.Allocator) Language {
    const file = openConfigLangFile(false);
    if (file) |f| {
        defer f.close();
        var buf: [16]u8 = undefined;
        const bytes_read = f.readAll(&buf) catch 0;
        const content = std.mem.trim(u8, buf[0..bytes_read], " \t\r\n");

        if (std.mem.eql(u8, content, "pt")) {
            return .pt;
        } else if (std.mem.eql(u8, content, "en")) {
            return .en;
        }
    }

    return detectSystemLanguage(allocator);
}

pub fn setLanguage(lang_str: []const u8) bool {
    const file = openConfigLangFile(true) orelse return false;
    defer file.close();

    if (std.mem.eql(u8, lang_str, "pt") or std.mem.eql(u8, lang_str, "pt_BR") or std.mem.eql(u8, lang_str, "pt-br")) {
        file.writeAll("pt\n") catch return false;
        return true;
    } else if (std.mem.eql(u8, lang_str, "en") or std.mem.eql(u8, lang_str, "en_US") or std.mem.eql(u8, lang_str, "en-us")) {
        file.writeAll("en\n") catch return false;
        return true;
    }

    return false;
}

pub fn getStrings(allocator: std.mem.Allocator) *const Strings {
    const lang = getLanguage(allocator);
    return switch (lang) {
        .pt => &pt_strings,
        .en => &en_strings,
    };
}
